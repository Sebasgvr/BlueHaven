create function public.bh_estado() returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare uid uuid := auth.uid(); perfil jsonb; catalogo jsonb; mochila jsonb;
begin
  if uid is null then raise exception 'Iniciá sesión para continuar.' using errcode='28000'; end if;
  select to_jsonb(p) into perfil from public.perfiles p where usuario_id=uid;
  if perfil is null then raise exception 'No se encontró tu perfil.'; end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',p.id,'nombre',p.nombre,'rareza',p.rareza,'velocidad',p.velocidad,
    'pesoSeleccion',p.peso_seleccion,'sprite',p.sprite,'datos',p.datos,
    'descubierto',c.usuario_id is not null,'cantidad_capturada',coalesce(c.cantidad_capturada,0),
    'mejorCalidadId',c.mejor_calidad_id,'mejorPrecio',c.mejor_precio
  ) order by p.id),'[]'::jsonb) into catalogo
  from public.peces p left join public.capturas_usuario c on c.pez_id=p.id and c.usuario_id=uid;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',i.id,'pez_id',p.id,'nombre',p.nombre,'rareza',p.rareza,'sprite',p.sprite,
    'calidadId',i.calidad_id,'capturaRiesgo',i.captura_riesgo,'precio',i.precio
  ) order by i.id),'[]'::jsonb) into mochila
  from public.inventario_peces i join public.peces p on p.id=i.pez_id where i.usuario_id=uid;
  return jsonb_build_object('perfil',perfil,'catalogo',catalogo,'inventario',mochila);
end;
$$;

create function public.bh_guardar_captura(p_pez_id bigint,p_calidad text,p_riesgo boolean,p_token uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); especie public.peces; previo public.eventos_captura;
  valor integer; multiplicador numeric; item_id bigint; cantidad integer;
begin
  if uid is null then raise exception 'Iniciá sesión para continuar.' using errcode='28000'; end if;
  if p_token is null or p_calidad is null or p_riesgo is null then raise exception 'Captura inválida.' using errcode='22023'; end if;
  perform 1 from public.perfiles where usuario_id=uid for update;
  if not found then raise exception 'Perfil inexistente.'; end if;
  select * into previo from public.eventos_captura where usuario_id=uid and token=p_token;
  if found then return jsonb_build_object('ok',true,'inventario_id',previo.inventario_id,'precio',previo.precio); end if;
  select * into especie from public.peces where id=p_pez_id;
  if not found then raise exception 'Especie inexistente.' using errcode='22023'; end if;
  multiplicador := case p_calidad when 'comun' then 1 when 'poco_comun' then 1.5 when 'raro' then 2.25 when 'epico' then 3.5 when 'legendario' then 5.5 end;
  if multiplicador is null then raise exception 'Calidad inválida.' using errcode='22023'; end if;
  valor := round((case especie.rareza when 1 then 50 when 2 then 120 when 3 then 300 when 4 then 800 when 5 then 2000 end) * multiplicador * (case when p_riesgo then 1.4 else 1 end));
  insert into public.capturas_usuario(usuario_id,pez_id,mejor_calidad_id,mejor_precio)
  values(uid,p_pez_id,p_calidad,valor)
  on conflict (usuario_id,pez_id) do update set
    cantidad_capturada=public.capturas_usuario.cantidad_capturada+1,
    mejor_calidad_id=case when excluded.mejor_precio > public.capturas_usuario.mejor_precio then excluded.mejor_calidad_id else public.capturas_usuario.mejor_calidad_id end,
    mejor_precio=greatest(public.capturas_usuario.mejor_precio,excluded.mejor_precio);
  select count(*) into cantidad from public.inventario_peces where usuario_id=uid;
  if cantidad < 10 then
    insert into public.inventario_peces(usuario_id,pez_id,calidad_id,captura_riesgo,precio)
    values(uid,p_pez_id,p_calidad,p_riesgo,valor) returning id into item_id;
  end if;
  insert into public.eventos_captura(usuario_id,token,inventario_id,precio) values(uid,p_token,item_id,valor);
  return jsonb_build_object('ok',true,'inventario_id',item_id,'precio',valor);
end;
$$;

create function public.bh_vender_pez(p_inventario_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); valor integer; saldo bigint;
begin
  if uid is null then raise exception 'Iniciá sesión para continuar.' using errcode='28000'; end if;
  perform 1 from public.perfiles where usuario_id=uid for update;
  delete from public.inventario_peces where id=p_inventario_id and usuario_id=uid returning precio into valor;
  if valor is null then raise exception 'Ese pez ya no está en tu mochila.' using errcode='22023'; end if;
  update public.perfiles set dinero=dinero+valor where usuario_id=uid returning dinero into saldo;
  return jsonb_build_object('ok',true,'precio',valor,'dinero',saldo);
end;
$$;
create function public.bh_vender_todos() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); valor bigint; saldo bigint;
begin
  if uid is null then raise exception 'Iniciá sesión para continuar.' using errcode='28000'; end if;
  perform 1 from public.perfiles where usuario_id=uid for update;
  with vendidos as (delete from public.inventario_peces where usuario_id=uid returning precio)
    select coalesce(sum(precio),0) into valor from vendidos;
  update public.perfiles set dinero=dinero+valor where usuario_id=uid returning dinero into saldo;
  return jsonb_build_object('ok',true,'total',valor,'dinero',saldo);
end;
$$;
create function public.bh_comprar_cana() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); perfil public.perfiles;
begin
  if uid is null then raise exception 'Iniciá sesión para continuar.' using errcode='28000'; end if;
  select * into perfil from public.perfiles where usuario_id=uid for update;
  if not found then raise exception 'Perfil inexistente.'; end if;
  if perfil.tiene_bambu then return jsonb_build_object('ok',true,'dinero',perfil.dinero); end if;
  if perfil.dinero < 150 then raise exception 'Necesitás $150 para la caña.' using errcode='22023'; end if;
  update public.perfiles set dinero=dinero-150,tiene_bambu=true where usuario_id=uid;
  return jsonb_build_object('ok',true,'dinero',perfil.dinero-150);
end;
$$;
create function public.bh_registrar_pregunta(p_pregunta text,p_respuesta text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'Iniciá sesión para continuar.' using errcode='28000'; end if;
  insert into public.preguntas_chatbot(usuario_id,pregunta,respuesta) values(auth.uid(),p_pregunta,p_respuesta);
end;
$$;
