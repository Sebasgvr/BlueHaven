begin;

create table public.perfiles (
  usuario_id uuid primary key references auth.users(id) on delete cascade,
  usuario text not null check (char_length(usuario) between 1 and 50),
  dinero bigint not null default 0 check (dinero >= 0),
  tiene_bambu boolean not null default false,
  creado_en timestamptz not null default now()
);
create table public.peces (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  rareza integer not null check (rareza between 1 and 5),
  velocidad real not null check (velocidad > 0),
  peso_seleccion real not null check (peso_seleccion > 0),
  sprite text,
  datos jsonb not null default '{}'::jsonb
);
create table public.capturas_usuario (
  usuario_id uuid not null references public.perfiles(usuario_id) on delete cascade,
  pez_id bigint not null references public.peces(id),
  cantidad_capturada integer not null default 1 check (cantidad_capturada > 0),
  mejor_calidad_id text not null default 'comun',
  mejor_precio integer not null default 0,
  primera_captura timestamptz not null default now(),
  primary key (usuario_id, pez_id)
);
create table public.inventario_peces (
  id bigint generated always as identity primary key,
  usuario_id uuid not null references public.perfiles(usuario_id) on delete cascade,
  pez_id bigint not null references public.peces(id),
  calidad_id text not null check (calidad_id in ('comun','poco_comun','raro','epico','legendario')),
  captura_riesgo boolean not null default false,
  precio integer not null check (precio > 0),
  creado_en timestamptz not null default now()
);
create index inventario_usuario_idx on public.inventario_peces(usuario_id);
create table public.eventos_captura (
  usuario_id uuid not null references public.perfiles(usuario_id) on delete cascade,
  token uuid not null,
  inventario_id bigint,
  precio integer not null,
  creado_en timestamptz not null default now(),
  primary key (usuario_id, token)
);
create table public.preguntas_chatbot (
  id bigint generated always as identity primary key,
  usuario_id uuid not null references public.perfiles(usuario_id) on delete cascade,
  pregunta text not null check (char_length(pregunta) between 1 and 300),
  respuesta text not null check (char_length(respuesta) <= 10000),
  creado_en timestamptz not null default now()
);
create index preguntas_usuario_idx on public.preguntas_chatbot(usuario_id);

create function public.bh_crear_perfil() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.perfiles(usuario_id, usuario)
  values (new.id, left(coalesce(nullif(trim(new.raw_user_meta_data->>'usuario'),''), 'Pescador'),50))
  on conflict (usuario_id) do nothing;
  return new;
end;
$$;
create trigger bluehaven_perfil_nuevo after insert on auth.users
for each row execute function public.bh_crear_perfil();
insert into public.perfiles(usuario_id,usuario)
select id,left(coalesce(nullif(trim(raw_user_meta_data->>'usuario'),''),'Pescador'),50)
from auth.users on conflict (usuario_id) do nothing;

